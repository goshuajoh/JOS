"""Step 1: write the schema's questions as static Pydantic enums the FSM can import.

The YAML schema stays the source of truth (descriptions are prompts, and calibration files
are fingerprinted against it). This module renders it as plain Python so FSM code gets
real types: `RowAction.NO_OP`, `RowAction.ASK_HUMAN`, `PosRowGateDecision(...)`.

    s1gate export-enums --schema configs/schema.pos.yaml --out s1gate/generated/pos_row_gate.py

The generated file carries the schema fingerprint; `check_generated` (and the test suite)
fails when the YAML changes and the module was not regenerated.
"""
from __future__ import annotations

import re
import keyword
import shlex
import textwrap
from pathlib import Path

from pydantic import BaseModel

from .schema import DecisionSchema, _camel, _enum_member

HEADER = '''"""Generated by `s1gate export-enums` from {source} - do not edit by hand.

Schema {name} v{version}, fingerprint {fingerprint}. Regenerate after any schema change:

    s1gate export-enums --schema {source_q} --out {out_q}
"""
from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, ConfigDict

SCHEMA_NAME = {name!r}
SCHEMA_VERSION = {version}
SCHEMA_FINGERPRINT = {fingerprint!r}
'''


def _escape(line: str) -> str:
    return line.replace("\\", "\\\\").replace('"""', "'''")


def _doc(text: str, indent: str = "    ") -> str:
    # wrap first, then escape each line: an escaped backslash pair is never split across lines
    lines = [_escape(x) for x in textwrap.wrap(" ".join(text.split()), width=92 - len(indent))] or [""]
    if len(lines) == 1:
        one = lines[0] + (" " if lines[0].endswith('"') else "")  # a quote before the delimiter ends it early
        return f'{indent}"""{one}"""'
    body = "\n".join(indent + line for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""'


def check_names(schema: DecisionSchema) -> list[str]:
    """Names that would make the generated module fail to compile or import."""
    problems = []
    model = _camel(schema.name) + "Decision"
    reserved = {"Enum", "BaseModel", "ConfigDict", model}
    classes: dict[str, str] = {}
    for q in schema.questions:
        if keyword.iskeyword(q.name) or keyword.issoftkeyword(q.name):
            problems.append(f"question {q.name!r} is a Python keyword")
        if q.name.startswith("model_") or hasattr(BaseModel, q.name):
            problems.append(f"question {q.name!r} clashes with a pydantic BaseModel attribute")
        cls = _camel(q.name)
        if cls in reserved or cls in classes:
            problems.append(f"question {q.name!r} becomes class {cls}, which "
                            + (f"question {classes[cls]!r} also becomes" if cls in classes else "the module already uses"))
        classes.setdefault(cls, q.name)
        members: dict[str, str] = {}
        for option in q.options:
            m = _enum_member(option)
            if m in members:
                problems.append(f"question {q.name!r}: options {members[m]!r} and {option!r} both become member {m}")
            members.setdefault(m, option)
    return problems


def render(schema: DecisionSchema, source: str = "configs/schema.pos.yaml",
           out: str = "s1gate/generated/pos_row_gate.py") -> str:
    problems = check_names(schema)
    if problems:
        raise ValueError("cannot generate enums: " + "; ".join(problems))
    parts = [HEADER.format(source=source, out=out, source_q=shlex.quote(source), out_q=shlex.quote(out),
                           name=schema.name, version=schema.version, fingerprint=schema.fingerprint())]
    fallbacks = []
    for q in schema.questions:
        cls = _camel(q.name)
        lines = ["", "", f"class {cls}(str, Enum):", _doc(f"{q.prompt} ({q.kind})"), ""]
        for option, desc in q.options.items():
            lines.append(f"    {_enum_member(option)} = {option!r}")
            if desc:
                lines.append(_doc(desc))
        parts.append("\n".join(lines) + "\n")
        if q.fallback is not None:
            fallbacks.append((q.name, cls, _enum_member(q.fallback)))

    model = _camel(schema.name) + "Decision"
    fields = "\n".join(f"    {q.name}: {_camel(q.name)}" for q in schema.questions)
    parts.append(f'''

class {model}(BaseModel):
    """One gate answer: exactly one option per question."""

    model_config = ConfigDict(frozen=True, extra="forbid")

{fields}
''')
    fb = "\n".join(f"    {n!r}: {c}.{m}," for n, c, m in fallbacks)
    parts.append(f'''

# what the gate returns for a question when confidence is under its threshold
FALLBACKS = {{
{fb}
}}

QUESTIONS = {{
''' + "\n".join(f"    {q.name!r}: {_camel(q.name)}," for q in schema.questions) + "\n}\n")
    return "".join(parts)


def _path(p) -> str:
    return _escape(Path(p).as_posix())


def write(schema_path: str, out_path: str) -> str:
    schema = DecisionSchema.load(schema_path)
    text = render(schema, source=_path(schema_path), out=_path(out_path))
    try:  # never write a module that does not import (the module defines enums and one model)
        exec(compile(text, str(out_path), "exec"), {"__name__": "s1gate_export_check"})
    except Exception as e:  # noqa: BLE001 - any failure here means the schema cannot be exported
        raise ValueError(f"the generated module would not import: {type(e).__name__}: {e}") from e
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(text, encoding="utf-8")
    init = Path(out_path).parent / "__init__.py"
    if not init.exists():
        init.write_text('"""Modules generated from decision schemas by `s1gate export-enums`."""\n')
    return text


def check_generated(schema: DecisionSchema, module_path: str | Path) -> str | None:
    """None when the generated module matches the schema, else a one-line reason."""
    path = Path(module_path)
    if not path.exists():
        return f"{path} does not exist; run s1gate export-enums"
    m = re.search(r"^SCHEMA_FINGERPRINT = '([0-9a-f]+)'", path.read_text(encoding="utf-8"), re.MULTILINE)
    if not m:
        return f"{path} has no SCHEMA_FINGERPRINT"
    if m.group(1) != schema.fingerprint():
        return (f"{path} was generated for fingerprint {m.group(1)}, schema is now "
                f"{schema.fingerprint()}; run s1gate export-enums")
    text = path.read_text(encoding="utf-8")
    try:
        compile(text, str(path), "exec")
    except SyntaxError as e:
        return f"{path} does not compile ({e.msg}, line {e.lineno}); regenerate it"
    # the header names the paths it was written with (they may contain spaces)
    src = re.search(r'^"""Generated by `s1gate export-enums` from (.+) - do not edit by hand\.$', text, re.M)
    source = src.group(1) if src else "configs/schema.pos.yaml"
    line = re.search(r"^    (s1gate export-enums --schema .+)$", text, re.M)
    try:
        argv = shlex.split(line.group(1)) if line else []
    except ValueError:
        argv = []
    out = argv[argv.index("--out") + 1] if "--out" in argv[:-1] else _path(path)
    try:
        expected = render(schema, source, out)
    except ValueError as e:
        return str(e)
    if text != expected:
        return (f"{path} differs from what this version of export-enums writes (edited by hand, or written "
                "by an older s1gate?); regenerate it")
    return None
